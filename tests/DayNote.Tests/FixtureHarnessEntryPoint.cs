using System;
using System.Threading.Tasks;
using Avalonia.Threading;
using DayNote.Services;
using DayNote.Tests.Services;
using DayNote.Tests.ViewModels;

namespace DayNote.Tests;

internal static class FixtureHarnessEntryPoint
{
    public static int Main(string[] args)
    {
        if (args.Length == 2 && args[0] is "--lease-claim-harness" or "--lease-close-harness")
        {
            try
            {
                DataRootGuard.Check(args[1]);
                if (args[0] == "--lease-close-harness")
                {
                    SingleInstanceLeaseTests.RunBoundedCloseProof(args[1]);
                    Console.WriteLine("LEASE-CLOSE-SETTLED");
                }
                else
                {
                    var claimed = SingleInstanceLease.TryAcquire(args[1], out var lease);
                    using (lease) Console.WriteLine(claimed ? "LEASE-CLAIMED" : "LEASE-REJECTED");
                }
                return 0;
            }
            catch (Exception error)
            {
                Console.Error.WriteLine(error);
                return 1;
            }
        }
        if (args.Length != 3 || args[0] != "--failed-fixture-harness")
            return AutoGenerated.XunitAutoGeneratedEntryPoint.Main(args);
        try
        {
            // One proof per disposable process: the main thread owns its headless dispatcher for
            // the entire fixture unwind. There is no shared test-session lifetime to reset afterward.
            TestAppBuilder.BuildAvaloniaApp().SetupWithoutStarting();
            var proving = MainWindowViewModelTests.RunFailedFixtureHarnessAsync(args[1], args[2]);
            if (!proving.IsCompleted)
            {
                var frame = new DispatcherFrame();
                _ = proving.ContinueWith(_ => Dispatcher.UIThread.Post(() => frame.Continue = false), TaskScheduler.Default);
                Dispatcher.UIThread.PushFrame(frame);
            }
            proving.GetAwaiter().GetResult();
            Console.WriteLine("FAILED-FIXTURE-SETTLED");
            return 0;
        }
        catch (Exception error)
        {
            Console.Error.WriteLine(error);
            return 1;
        }
    }
}
